"""JSON and HTML report artifact tests."""

from __future__ import annotations

import json
from typing import Any

from evalgate.models.result import RunReport
from evalgate.providers.mock import MockProvider
from evalgate.report.html_report import render_html
from evalgate.report.json_report import render_json
from evalgate.runner.engine import run_suite


async def _report(make_suite: Any) -> RunReport:
    loaded = make_suite(
        cases=[
            {"id": "c00", "input": "one", "expected": "ok"},
            {"id": "c01", "input": "two", "expected": "ok"},
        ],
        metrics="  - type: regex\n    pattern: refund\n",
    )
    return await run_suite(loaded, MockProvider())


async def test_json_round_trips(make_suite: Any) -> None:
    report = await _report(make_suite)
    payload = json.loads(render_json(report))
    restored = RunReport.model_validate(payload)
    assert restored.suite_name == report.suite_name
    assert restored.summary.total == 2
    assert restored.cases[0].metrics[0].metric == "regex"


async def test_json_includes_failing_detail(make_suite: Any) -> None:
    report = await _report(make_suite)
    payload = json.loads(render_json(report))
    assert payload["cases"][0]["passed"] is False
    assert "pattern 'refund' not found" in payload["cases"][0]["metrics"][0]["detail"]


async def test_html_is_standalone_and_contains_cases(make_suite: Any) -> None:
    report = await _report(make_suite)
    html = render_html(report)
    assert "<!doctype html>" in html
    assert "c00" in html
    assert "refund" in html
    assert "Wilson 95% CI" in html
    assert "Generated by EvalGate" in html


async def test_html_escapes_untrusted_content(make_suite: Any) -> None:
    loaded = make_suite(
        cases=[{"id": "<script>alert(1)</script>", "input": "x", "expected": "ok"}],
        metrics="  - type: regex\n    pattern: refund\n",
    )
    report = await run_suite(loaded, MockProvider())
    html = render_html(report)
    assert "<script>alert(1)</script>" not in html
    assert "&lt;script&gt;alert(1)&lt;/script&gt;" in html


async def test_html_shows_hard_limit_breach(make_suite: Any) -> None:
    loaded = make_suite(
        cases=[{"id": "c00", "input": "x", "expected": "ok"}],
        suite_extra="limits:\n  max_p95_latency_ms: 1\n",
    )
    provider = MockProvider(simulated_latency_ms=50)
    report = await run_suite(loaded, provider)
    html = render_html(report)
    assert "Hard limit breached" in html
    assert "p95 latency" in html
